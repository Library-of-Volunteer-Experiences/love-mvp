// ─────────────────────────────────────────────────────────────
// LOVE — Library of Volunteer Experiences
// Shared Data Models
// ─────────────────────────────────────────────────────────────
// These TypeScript interfaces represent the future data models
// for the LOVE platform. No database implementation yet —
// these serve as the single source of truth for data shapes
// across web, mobile, and backend packages.
// ─────────────────────────────────────────────────────────────

import type {
  CAUSES,
  DISTANCE_OPTIONS,
  FREE_TIMES,
  MATCH_STATUS,
  NONPROFIT_MEMBER_ROLES,
  NOTIFICATION_CHANNELS,
  SKILLS,
  USER_ROLES,
} from './constants';

/**
 * Represents a volunteer user on the LOVE platform.
 *
 * Volunteers describe their skills in natural language.
 * Future AI systems will parse `skillDescription` to extract
 * structured skills, generate embeddings, and match against
 * event requirements.
 */
export interface Volunteer {
  /** Unique identifier */
  id: string;
  /** Full legal name */
  fullName: string;
  /** Email address (unique, used for auth) */
  email: string;
  /** Phone number */
  phone: string;
  /** Date of birth (ISO 8601 date string) */
  dob: string;
  /** Physical address */
  address: Address;
  /** Availability windows */
  availability: Availability[];
  /**
   * Free-text description of the volunteer's skills.
   *
   * Examples:
   * - "I teach kids math."
   * - "I have construction experience."
   * - "I can use Excel."
   * - "I speak Spanish."
   *
   * Future AI integration point: This field will be processed
   * by the skill extraction pipeline to generate structured
   * skill tags and embedding vectors.
   */
  skillDescription: string;
  /**
   * Maximum distance (in miles) the volunteer is willing
   * to travel for opportunities.
   */
  matchRadius: number;
  /** ISO 8601 timestamp */
  createdAt: string;
  /** ISO 8601 timestamp */
  updatedAt: string;
}

/**
 * Represents a nonprofit organization.
 *
 * Multiple users can be associated with a single nonprofit.
 * This supports future multi-user management per organization.
 */
export interface Nonprofit {
  /** Unique identifier */
  id: string;
  /** Organization name */
  name: string;
  /** Description of the organization's mission */
  description: string;
  /** Contact phone number */
  phone: string;
  /** Contact email address */
  email: string;
  /** Organization website URL */
  website: string;
  /** Physical office address */
  officeAddress: Address;
  /** URL to the organization's logo */
  logoUrl: string;
  /** ISO 8601 timestamp */
  createdAt: string;
  /** ISO 8601 timestamp */
  updatedAt: string;
}

/**
 * Represents a volunteer event/opportunity.
 *
 * Events are created by nonprofits and describe what
 * volunteers are needed for, when, and where.
 */
export interface Event {
  /** Unique identifier */
  id: string;
  /** Event name */
  name: string;
  /** Detailed description of the event */
  description: string;
  /** Full address or venue name */
  location: string;
  /** City */
  city: string;
  /** ZIP code */
  zipCode: string;
  /** Event start time (ISO 8601) */
  startTime: string;
  /** Event end time (ISO 8601) */
  endTime: string;
  /** Maximum number of volunteers */
  capacity: number;
  /**
   * Skills that would be nice to have (natural language).
   * AI matching will treat these as soft requirements.
   */
  desiredSkills: string[];
  /**
   * Skills that are mandatory (natural language).
   * AI matching will treat these as hard requirements.
   */
  requiredSkills: string[];
  /** Contact info for the event coordinator */
  coordinatorContact: ContactInfo;
  /** The nonprofit hosting this event */
  nonprofitId: string;
  /** ISO 8601 timestamp */
  createdAt: string;
  /** ISO 8601 timestamp */
  updatedAt: string;
}

/**
 * Represents a match between a volunteer and an event.
 *
 * Future AI integration point: The matching system will
 * populate `matchScore` and `matchReason` based on:
 * - Skill embedding similarity
 * - Geographic proximity
 * - Availability overlap
 * - Historical engagement patterns
 */
export interface OpportunityMatch {
  /** Unique identifier */
  id: string;
  /** Reference to the volunteer */
  volunteerId: string;
  /** Reference to the event */
  eventId: string;
  /**
   * Numeric score (0-100) indicating match quality.
   * Higher = better match.
   * Generated by the AI matching pipeline.
   */
  matchScore: number;
  /**
   * Human-readable explanation of why this match was made.
   * Generated by the AI matching pipeline.
   *
   * Example: "Volunteer has construction experience matching
   * the required skill 'general construction'. Distance: 3.2 miles.
   * Availability overlaps with event schedule."
   */
  matchReason: string;
  /** Match status */
  status: MatchStatus;
  /** ISO 8601 timestamp */
  createdAt: string;
  /** ISO 8601 timestamp */
  updatedAt: string;
}

// ─────────────────────────────────────────────────────────────
// Supporting Types
// ─────────────────────────────────────────────────────────────

export interface Address {
  street: string;
  city: string;
  state: string;
  zipCode: string;
  country: string;
}

export interface ContactInfo {
  name: string;
  email: string;
  phone: string;
}

export interface Availability {
  /** Day of the week (0 = Sunday, 6 = Saturday) */
  dayOfWeek: number;
  /** Start time in HH:mm format */
  startTime: string;
  /** End time in HH:mm format */
  endTime: string;
}

export type MatchStatus = (typeof MATCH_STATUS)[number];

// ─────────────────────────────────────────────────────────────
// Volunteer Preferences
// ─────────────────────────────────────────────────────────────

export type Cause = (typeof CAUSES)[number]['value'];
export type Skill = (typeof SKILLS)[number]['value'];
export type FreeTime = (typeof FREE_TIMES)[number]['value'];
export type DistanceOption = (typeof DISTANCE_OPTIONS)[number]['value'];

// ─────────────────────────────────────────────────────────────
// User Roles & Auth
// ─────────────────────────────────────────────────────────────

export type UserRole = (typeof USER_ROLES)[number];

/**
 * Role a user holds *within* a specific nonprofit organization.
 * A nonprofit can have many users; one user can belong to many
 * nonprofits (e.g. a board member who helps two charities).
 */
export type NonprofitMemberRole = (typeof NONPROFIT_MEMBER_ROLES)[number];

/**
 * Links a user account to a nonprofit organization.
 * Future multi-user-per-organization support is modeled here
 * rather than as a single `nonprofitId` on the user.
 */
export interface OrganizationMembership {
  id: string;
  userId: string;
  nonprofitId: string;
  memberRole: NonprofitMemberRole;
  /** ISO 8601 timestamp */
  createdAt: string;
  /** ISO 8601 timestamp */
  updatedAt: string;
}

/**
 * The authenticated principal as seen by application code.
 * Produced by an AuthProvider; never constructed from client input.
 */
export interface UserSession {
  userId: string;
  email: string;
  role: UserRole;
  /** Nonprofit memberships (empty for volunteers/admins). */
  memberships: Pick<OrganizationMembership, 'nonprofitId' | 'memberRole'>[];
  /** Whether the user completed an MFA challenge for this session. */
  mfaVerified: boolean;
  /** ISO 8601 timestamp when the session was issued (absolute timeout). */
  issuedAt: string;
  /** ISO 8601 timestamp of last activity (idle timeout). */
  lastActivityAt: string;
  /** ISO 8601 expiry timestamp */
  expiresAt: string;
}

// ─────────────────────────────────────────────────────────────
// Notification Types
// ─────────────────────────────────────────────────────────────

export type NotificationChannel = (typeof NOTIFICATION_CHANNELS)[number];

export interface Notification {
  id: string;
  recipientId: string;
  channel: NotificationChannel;
  subject: string;
  body: string;
  sentAt?: string;
  readAt?: string;
}

// ─────────────────────────────────────────────────────────────
// AI / Skill Matching Types (future)
// ─────────────────────────────────────────────────────────────

/**
 * Represents a structured skill extracted from natural language.
 * Future AI integration point.
 */
export interface ExtractedSkill {
  /** Raw text from the volunteer's description */
  rawText: string;
  /** Normalized skill category */
  category: string;
  /** Confidence score (0-1) of the extraction */
  confidence: number;
  /** Embedding vector for semantic matching */
  embedding?: number[];
}

/**
 * AI-derived skill data for a volunteer, stored separately from the
 * Volunteer record so that:
 * - the user's own words (`Volunteer.skillDescription`) are never overwritten
 * - derived data can be regenerated when the model/version changes
 * - AI output can be deleted independently (privacy requests)
 * Future AI integration point — see docs/architecture/ai-matching.md.
 */
export interface VolunteerSkillProfile {
  volunteerId: string;
  extractedSkills: ExtractedSkill[];
  /** Identifier of the extraction model + prompt version that produced this */
  extractorVersion: string;
  /** Identifier of the embedding model that produced the vectors */
  embeddingModel?: string;
  /** ISO 8601 timestamp */
  processedAt: string;
}

/**
 * Configuration for the AI matching pipeline.
 * Future AI integration point.
 */
export interface MatchingConfig {
  /** Minimum match score threshold (0-100) */
  minScore: number;
  /** Maximum number of matches to return per volunteer */
  maxMatches: number;
  /** Weight for skill similarity (0-1) */
  skillWeight: number;
  /** Weight for geographic proximity (0-1) */
  distanceWeight: number;
  /** Weight for availability overlap (0-1) */
  availabilityWeight: number;
}
